#!/usr/bin/env python3
"""Pure fresh-water transcription, 60 updates/s. Not game execution or bit-exact.

Fixed topology: pump N0->N1, radiator N1<->R<->N2, manifold N2<->M<->N0.
Component order and initial fills are explicit analyst inputs, not universal defaults.
The engine is held at a prescribed temperature. This measures the cooling load
that this selected loop can accept, not the heat generated by a running engine.
"""
from dataclasses import dataclass
import argparse,json,math


def clamp(x,a,b): return max(a,min(b,x))

@dataclass
class State:
    volume: float
    amount: float
    temperature: float = 20.
    def window(self):
        if self.volume <= 8: return self.amount
        return max(self.amount*4/(60*self.volume),self.amount-self.volume+8)
    def pressure(self): return 60*self.window()/min(self.volume,8)

@dataclass
class Port:
    node: str
    demand: float = 0.
    allocated: float = 0.


def demand(a,b,bias=0.,one_way=False,port=False):
    """Sign positive A->B. Single-port bias has opposite sign from pump bias."""
    wa,wb=min(a.volume,8),min(b.volume,8)
    ga,gb=a.window(),b.window()
    pa,pb=a.pressure(),b.pressure()
    z=pa-pb+(-bias if port else bias)
    if one_way and z<0: z=0.
    mean=(pa*wa+pb*wb)/(wa+wb)
    if z>0:
        t=clamp(clamp(mean+(bias if port else -bias),pa-20,pa+20),0,60)
        return min((1-t/pa)*ga if pa>0 else 0.,wb-gb)
    if z<0:
        t=clamp(clamp(mean+(-bias if port else bias),pb-20,pb+20),0,60)
        return max(-(1-t/pb)*gb if pb>0 else 0.,-(wa-ga))
    return 0.


def transfer(a,b,q,fallback=False):
    """Signed transfer, using recipient POST-transfer amount per native assembly."""
    if q<0: return -transfer(b,a,-q,fallback)
    if q<=0: return 0.
    q=min(q,a.amount)
    td=a.temperature
    a.amount=max(0.,a.amount-q);b.amount+=q
    if b.amount+q>.001:
        b.temperature=(b.amount*b.temperature+q*td)/(b.amount+q)
    elif fallback:b.temperature=td
    return q


def diffuse(a,b,q,factor=1.):
    """0x1402ed390; pure species means composition is unchanged."""
    if a.amount<=1e-4 or b.amount<=1e-4: return
    e=min(.1*factor*max(0.,1-abs(q)/.01),a.amount,b.amount)
    a.temperature+=e/a.volume*(b.temperature-a.temperature)
    b.temperature+=e/b.volume*(a.temperature-b.temperature)


def allocate(nodes,ports):
    for key,a in nodes.items():
        pp=[p for p in ports if p.node==key]
        positive=sum(max(0,p.demand) for p in pp)
        negative=sum(max(0,-p.demand) for p in pp)
        so=min(1.,a.amount/positive) if positive>0 else 1.
        si=min(1.,(a.volume-a.amount)/negative) if negative>0 else 1.
        for p in pp:
            d=p.demand
            p.allocated=d*abs(d)/(positive if d>0 else negative)*(so if d>0 else si) if d else 0.
            p.demand=0.


def bridge(nodes,p1,p2,bias,one_way=True,factor=1.):
    if p1.node==p2.node:return 0.
    a,b=nodes[p1.node],nodes[p2.node]
    d=demand(a,b,bias,one_way)
    p1.demand=d;p2.demand=-d
    x,y=p1.allocated,p2.allocated;p1.allocated=p2.allocated=0.
    q=min(x,-y) if x>0 and y<0 else max(x,-y) if x<0 and y>0 else 0.
    q=clamp(q,-.5*factor*abs(d),.5*factor*abs(d))
    if one_way and q<=0:q=0.
    if q>0:q=min(q,a.window())
    if q<0:q=max(q,-b.window())
    q=transfer(a,b,q,fallback=True)
    if not one_way:diffuse(a,b,q,factor)
    return q


def exchange(nodes,p,b):
    a=nodes[p.node]
    d=demand(a,b,port=True);p.demand=d
    q=clamp(p.allocated,-.5*abs(d),.5*abs(d));p.allocated=0.
    if q>0:q=min(q,a.window(),min(b.volume,8))
    if q<0:q=max(q,-b.amount,-1.)
    q=transfer(a,b,q)
    # Native single-port call supplies B as first diffusion argument, A second.
    diffuse(b,a,q)
    return q


def run(bias=10.,seconds=600,engine_temperature=115.,fan=2.,cylinder_voxels=27,
        radiator_volume=9.,network_fill=0.,radiator_fill=1.):
    capacity=1+40*cylinder_voxels;vc=.01*capacity+1
    nodes={k:State(4,4*network_fill) for k in ['N0','N1','N2']}
    rad=State(radiator_volume,radiator_volume*radiator_fill)
    manifold=State(vc,vc)
    ports=[Port(k) for k in ['N0','N1','N1','N2','N2','N0']]
    n=int(seconds*60);recent=[];m0=sum(s.amount for s in nodes.values())+rad.amount+manifold.amount
    for tick in range(n):
        allocate(nodes,ports)
        q=bridge(nodes,ports[0],ports[1],bias)
        r0=exchange(nodes,ports[2],rad);r1=exchange(nodes,ports[3],rad)
        rad.temperature+=.003*(1+fan)*(20.-rad.temperature)
        c0=exchange(nodes,ports[4],manifold);c1=exchange(nodes,ports[5],manifold)
        # 0x1404cb790, held-engine boundary replaces engine heat/RPS dynamics.
        h=.04*manifold.amount*(engine_temperature-manifold.temperature)
        manifold.temperature+=.04*(engine_temperature-manifold.temperature) if manifold.amount>0 else 0.
        if tick>=n-60:recent.append([q,r0,r1,c0,c1,h])
    m1=sum(s.amount for s in nodes.values())+rad.amount+manifold.amount
    assert abs(m1-m0)<1e-7,(m0,m1)
    return dict(seconds=seconds,bias=bias,engine_temperature=engine_temperature,fan=fan,
        capacity=capacity,initial_network_fill=network_fill,initial_radiator_fill=radiator_fill,
        initial_total_amount=m0,final_total_amount=m1,
        nodes={k:vars(v)|{'pressure':v.pressure()} for k,v in nodes.items()},
        radiator=vars(rad)|{'pressure':rad.pressure()},manifold=vars(manifold)|{'pressure':manifold.pressure()},
        last_second_mean=dict(zip(['pump_amount_per_update','rad_port0','rad_port1','manifold_port0','manifold_port1','engine_heat_per_update'],[sum(v[i] for v in recent)/len(recent) for i in range(6)])),
        phase_sample_manifold_minus_radiator=manifold.temperature-rad.temperature)

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--seconds',type=float,default=600);ap.add_argument('--bias',type=float,default=10)
    ap.add_argument('--network-fill',type=float,default=0);ap.add_argument('--radiator-fill',type=float,default=1)
    a=ap.parse_args();print(json.dumps(run(**vars(a)),indent=2,allow_nan=False))
